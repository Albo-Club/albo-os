#!/usr/bin/env node
// Bundle docs/produit/*.md into a TypeScript module the Convex bundler can
// import.
//
// The product documentation is read in two places: the in-app reader and ⌘K
// (Vite) and the AI assistant (Convex functions, bundled by esbuild). esbuild
// has no loader for `.md` and Convex does not let us add one, so the folder
// cannot be imported from `convex/` as-is. This script writes the pages as
// string literals into `convex/lib/productDocs.generated.ts`, which both
// sides import through `convex/lib/productDocs.ts` — the UI and the assistant
// therefore read the very same text.
//
// The output is gitignored and regenerated on every `pnpm install`
// (postinstall) and at `pnpm dev` startup: no diff noise on doc PRs, no CI
// check to keep, nothing to drift. A page added to the folder shows up at the
// next run, nothing to register. See KNOWN_ISSUES.md § « Documentation
// produit côté Convex ».
//
// Usage: node scripts/gen-product-docs.mjs   (or `pnpm gen:docs`)

import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const DOCS_DIR = resolve(ROOT, 'docs/produit')
const OUT = resolve(ROOT, 'convex/lib/productDocs.generated.ts')

// Pages are numbered (`01-…`, `20-…`), so the file name is the reading order.
const files = (await readdir(DOCS_DIR))
  .filter((file) => file.endsWith('.md'))
  .sort()

const docs = []
for (const file of files) {
  const markdown = await readFile(resolve(DOCS_DIR, file), 'utf8')
  const slug = file.replace(/\.md$/, '')
  // First `# …` line, falling back to the slug when a page has no H1.
  const title = markdown.match(/^#\s+(.+)$/m)?.[1].trim() ?? slug
  docs.push({ slug, title, markdown })
}

const output = [
  '// GENERATED by scripts/gen-product-docs.mjs — do not edit.',
  '// Source: docs/produit/*.md. Regenerated by `pnpm install` and `pnpm dev`.',
  '',
  'export type ProductDocSource = {',
  '  /** File name without extension, e.g. `05-deals` — the URL param. */',
  '  slug: string',
  "  /** The page's H1, e.g. « Deals ». */",
  '  title: string',
  '  markdown: string',
  '}',
  '',
  'export const PRODUCT_DOCS: Array<ProductDocSource> = [',
  ...docs.map((doc) => `  ${JSON.stringify(doc)},`),
  ']',
  '',
].join('\n')

// Skip the write when nothing changed, so a `pnpm install` run next to a live
// `convex dev` does not trigger a pointless redeploy.
const current = await readFile(OUT, 'utf8').catch(() => null)
if (current === output) {
  console.log(`[gen-product-docs] ${docs.length} pages, up to date`)
} else {
  await writeFile(OUT, output)
  console.log(
    `[gen-product-docs] ${docs.length} pages → convex/lib/productDocs.generated.ts`,
  )
}
